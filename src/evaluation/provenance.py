"""Data provenance tagging, and the guard that stops incompatible evidence being mixed.

Why this module exists
----------------------
The project's headline failure mode (docs/00_INVESTIGATION_REPORT.md section 3) was
reporting synthetic results as if they were evidence about the real world. Rules in a
README do not prevent that; code does. Every table of metrics therefore carries a
provenance tag, and `require_single_provenance` refuses to emit a table that mixes
real measurements with simulated ones unless the caller explicitly and visibly
overrides it.

Three tags, and they are not interchangeable:

REAL         every input traces to a physical measurement or a third-party dataset.
SYNTHETIC    any input was generated by our own code. Proves the pipeline runs;
             says nothing about accuracy in the world.
COUPLED-SIM  real measurements propagated through a model that links two datasets
             which cannot legitimately be joined row-wise -- specifically the
             SoH -> range study (RQ3), where the consumption side and the battery
             side come from different vehicles entirely. Real inputs, simulated
             coupling. It is NOT end-to-end validation and must never be described
             as such.
"""
from __future__ import annotations

from dataclasses import dataclass, field
from enum import Enum

import pandas as pd

PROVENANCE_COLUMN = "provenance"
SOURCE_COLUMN = "source_dataset"


class Provenance(str, Enum):
    REAL = "REAL"
    SYNTHETIC = "SYNTHETIC"
    COUPLED_SIM = "COUPLED-SIM"

    def permits_demonstrated_claim(self) -> bool:
        """Only REAL data can support a 'we demonstrated X' claim."""
        return self is Provenance.REAL


class ProvenanceError(RuntimeError):
    """Raised when evidence of different kinds would be silently combined."""


class ConclusionType(str, Enum):
    DEMONSTRATED = "DEMONSTRATED"  # measured on real data under a declared split
    SIMULATED = "SIMULATED"        # involves synthetic data or a simulated coupling
    ASSUMED = "ASSUMED"            # rests on an imposed constant or modelling choice


def tag(df: pd.DataFrame, provenance: Provenance, source_dataset: str) -> pd.DataFrame:
    """Return a copy of `df` carrying its provenance. Loaders must call this."""
    out = df.copy()
    out[PROVENANCE_COLUMN] = Provenance(provenance).value
    out[SOURCE_COLUMN] = source_dataset
    return out


def provenances_of(df: pd.DataFrame) -> set[Provenance]:
    if PROVENANCE_COLUMN not in df.columns:
        raise ProvenanceError(
            f"DataFrame has no '{PROVENANCE_COLUMN}' column. Every table that reaches "
            f"evaluation must be tagged by its loader via provenance.tag()."
        )
    return {Provenance(v) for v in df[PROVENANCE_COLUMN].unique()}


def require_single_provenance(df: pd.DataFrame, *, allow_mixed: bool = False) -> Provenance:
    """Return the single provenance of `df`, or refuse.

    `allow_mixed=True` is deliberately awkward: mixing provenance is occasionally
    legitimate (a figure comparing synthetic and real results side by side), but it
    should be a visible decision at the call site, never a default.
    """
    found = provenances_of(df)
    if len(found) > 1 and not allow_mixed:
        names = ", ".join(sorted(p.value for p in found))
        raise ProvenanceError(
            f"Refusing to combine data of different provenance: {names}. "
            f"Real measurements and simulated data do not support the same claims. "
            f"Pass allow_mixed=True only if the resulting figure labels both."
        )
    if Provenance.SYNTHETIC in found:
        return Provenance.SYNTHETIC
    if Provenance.COUPLED_SIM in found:
        return Provenance.COUPLED_SIM
    return Provenance.REAL


def check_conclusion(provenance: Provenance, conclusion: ConclusionType) -> None:
    """Refuse a claim the data cannot support."""
    if conclusion is ConclusionType.DEMONSTRATED and not provenance.permits_demonstrated_claim():
        raise ProvenanceError(
            f"Cannot report a DEMONSTRATED conclusion from {provenance.value} data. "
            f"Use ConclusionType.SIMULATED and label the result accordingly."
        )


@dataclass
class Evidence:
    """The provenance block every experiment must publish alongside its numbers.

    Written to reports/<exp_id>/EVIDENCE.md. It forces each experiment to state,
    in one place, what was measured, what was computed, what was assumed, and how
    strong a claim the result supports.
    """

    experiment: str
    measured: list[str] = field(default_factory=list)       # M: sensor signals
    derived: list[str] = field(default_factory=list)        # D: computed, with transform
    external: list[str] = field(default_factory=list)       # X: third-party datasets
    simulated: list[str] = field(default_factory=list)      # S: generated by us
    assumptions: list[str] = field(default_factory=list)    # A: imposed constants/choices
    split_protocol: str = ""
    n: str = ""
    provenance: Provenance = Provenance.REAL
    conclusion_type: ConclusionType = ConclusionType.DEMONSTRATED
    claim_strength: str = "association-only"
    known_confounds: list[str] = field(default_factory=list)

    def __post_init__(self) -> None:
        check_conclusion(self.provenance, self.conclusion_type)

    def to_markdown(self) -> str:
        def block(title: str, items: list[str]) -> str:
            if not items:
                return f"**{title}:** none\n"
            return f"**{title}:**\n" + "".join(f"- {i}\n" for i in items)

        parts = [
            f"# Evidence — {self.experiment}\n",
            f"**Provenance:** `{self.provenance.value}`  ",
            f"**Conclusion type:** `{self.conclusion_type.value}`  ",
            f"**Claim strength:** {self.claim_strength}\n",
            block("Measured (M)", self.measured),
            block("Derived (D)", self.derived),
            block("External (X)", self.external),
            block("Simulated (S)", self.simulated),
            block("Assumptions (A)", self.assumptions),
            f"\n**Split protocol:** {self.split_protocol}\n",
            f"**n:** {self.n}\n",
            block("Known confounds", self.known_confounds),
        ]
        if self.provenance is Provenance.COUPLED_SIM:
            parts.append(
                "\n> ⚠️ **COUPLED-SIM.** Real inputs propagated through a simulated "
                "coupling between datasets that cannot be joined row-wise. This is a "
                "propagation study, **not** real-world end-to-end validation.\n"
            )
        if self.claim_strength == "association-only":
            parts.append(
                "\n> Observational data: associations only. No causal claim is made.\n"
            )
        return "".join(parts)
